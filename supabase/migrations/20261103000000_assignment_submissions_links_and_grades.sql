alter table public.assignment_submissions
  add column if not exists link_entrega text,
  add column if not exists grade numeric(5,2),
  add column if not exists feedback text;

alter table public.assignment_submissions
  add constraint assignment_submissions_grade_range
  check (grade is null or (grade >= 0 and grade <= 100));

create table if not exists public.tutor_interactions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create index if not exists tutor_interactions_created_at_idx
  on public.tutor_interactions (created_at desc);

alter table public.tutor_interactions enable row level security;

